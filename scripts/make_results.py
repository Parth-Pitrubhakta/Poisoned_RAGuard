"""Regenerate the tables in experiments/RESULTS.md from experiments/index.json + each run's summary/traces.

Only the block between the TABLES markers is rewritten; hand-written text around it is kept.
For each (retriever, reranker, llm) the latest *complete* matrix run (run_name nq_*_full) is used.

  uv run python scripts/make_results.py
"""
import json
import re
from pathlib import Path

from prag.eval.metrics import attack_success_normalized as norm_hit

ROOT = Path(__file__).resolve().parents[1]
EXP = ROOT / "experiments"
OUT = EXP / "RESULTS.md"
START, END = "<!-- TABLES:START (generated by scripts/make_results.py) -->", "<!-- TABLES:END -->"

LLM_ORDER = ["vicuna-7b-v1.3", "qwen3.5-27b", "gpt-oss-120b"]
LLM_NAME = {"vicuna-7b-v1.3": "Vicuna-7B v1.3", "qwen3.5-27b": "Qwen3.5-27B", "gpt-oss-120b": "gpt-oss-120b"}


def ret_label(r):
    base = {"contriever": "Contriever (paper)", "qwen3-emb-8b": "Qwen3-Embedding-8B"}.get(r["retriever"], r["retriever"])
    return base + (f" + {r['reranker']}" if r.get("reranker") else "")


def trace_stats(path):
    T = [json.loads(l) for l in open(path / "traces.jsonl")]
    n = len(T)
    u = [t["usage"]["poisoned"] for t in T]
    in_reason_only = sum(1 for t, g in zip(T, u) if not t["success"] and g.get("reasoning")
                         and t["target_answer"].lower() in g["reasoning"].lower())
    done = [t for t in T if t["output_poisoned"].strip()]
    return {"n": n, "empty": sum(not t["output_poisoned"].strip() for t in T) / n,
            "asr_norm": sum(norm_hit(t["target_answer"], t["output_poisoned"]) for t in T) / n,
            "asr_answered": (sum(t["success"] for t in done) / len(done)) if done else float("nan"),
            "clean_norm": sum(norm_hit(t["correct_answer"], t["output_clean"] or "") for t in T) / n,
            "trunc": sum(g["finish_reason"] == "length" for g in u) / n,
            "mean_ctok": sum(g["completion_tokens"] for g in u) / n,
            "reason_only": in_reason_only / n,
            "clean_empty": sum(not (t["output_clean"] or "").strip() for t in T) / n}


def main():
    idx = json.loads((EXP / "index.json").read_text())["runs"]
    runs = {}
    for r in idx:
        if r.get("kind") != "pipeline" or r.get("status") != "complete" or not r["run_id"].startswith("nq_"):
            continue
        if (r.get("defense") or "none") != "none" or r.get("top_k", 5) != 5:  # Step 5 defended runs: scripts/make_defense_results.py
            continue
        runs[(ret_label(r), r["llm"])] = r  # later entries win (latest)
    if not runs:
        raise SystemExit("no complete matrix runs in experiments/index.json")
    rows = list(dict.fromkeys(k[0] for k in sorted(runs, key=lambda k: (k[0].count("+"), "Qwen" in k[0]))))
    cols = [l for l in LLM_ORDER if any(k[1] == l for k in runs)]
    summ = {k: json.loads((ROOT / r["path"] / "summary.json").read_text()) for k, r in runs.items()}
    stats = {k: trace_stats(ROOT / r["path"]) for k, r in runs.items()}

    def grid(title, fn, fmt="{:.2f}"):
        out = [f"**{title}**", "", "| Retriever | " + " | ".join(LLM_NAME[c] for c in cols) + " |",
               "|---|" + "---|" * len(cols)]
        for row in rows:
            cells = [fmt.format(fn((row, c))) if (row, c) in runs else "—" for c in cols]
            out.append(f"| {row} | " + " | ".join(cells) + " |")
        return out + [""]

    L = [START, ""]
    L += grid("Table 1 — ASR (attack success rate; upstream substring metric on the final answer)",
              lambda k: summ[k]["metrics"]["asr_mean"])
    L += grid("Table 1b — ASR, typography-normalized (secondary, NOT upstream: NFKC + ASCII quotes/dashes + collapsed whitespace)",
              lambda k: stats[k]["asr_norm"])
    L += grid("Table 1c — ASR among questions with a non-empty final answer (upstream metric; excludes truncated reasoning)",
              lambda k: stats[k]["asr_answered"])
    L += grid("Table 2 — Clean accuracy (no poison; correct answer in the final answer)", lambda k: summ[k]["clean_accuracy"])
    L += grid("Table 2b — Clean accuracy, typography-normalized (secondary)", lambda k: stats[k]["clean_norm"])
    L += grid("Table 3 — Clean says target (no poison, target answer already in the output)",
              lambda k: summ[k]["clean_says_target_rate"])
    L += ["**Table 4 — Retrieval of poison (LLM-independent; P = own poison in top-5 / 5, R = / N=5)**", "",
          "| Retriever | Precision | Recall | F1 | identical across LLMs |", "|---|---|---|---|---|"]
    for row in rows:
        ks = [(row, c) for c in cols if (row, c) in runs]
        m = [summ[k]["metrics"] for k in ks]
        same = len({json.dumps(x["ret_counts"]) for x in m}) == 1
        L.append(f"| {row} | {m[0]['precision_mean']:.2f} | {m[0]['recall_mean']:.2f} | {m[0]['f1_mean']:.2f} | {'yes' if same else 'NO'} |")
    L += ["", "**Table 5 — Generation diagnostics (poisoned prompts)**", "",
          "| Retriever | LLM | empty final answer | truncated (finish=length) | failed, target in reasoning | mean completion tokens | gen time (s) |",
          "|---|---|---|---|---|---|---|"]
    for row in rows:
        for c in cols:
            if (row, c) in runs:
                s, st = summ[(row, c)], stats[(row, c)]
                L.append(f"| {row} | {LLM_NAME[c]} | {st['empty']:.2f} | {st['trunc']:.2f} | {st['reason_only']:.2f} | "
                         f"{st['mean_ctok']:.0f} | {s['timing_s']['generation']:.0f} |")
    L += ["", "**Runs used**", "", "| Retriever | LLM | run_id | ASR per iteration |", "|---|---|---|---|"]
    for k, r in sorted(runs.items()):
        L.append(f"| {k[0]} | {LLM_NAME[k[1]]} | `{r['run_id']}` | {', '.join(f'{x:.1f}' for x in summ[k]['metrics']['asr_per_iter'])} |")
    L += ["", END]
    block = "\n".join(L)
    text = OUT.read_text() if OUT.exists() else f"# RESULTS\n\n{START}\n{END}\n"
    text = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    OUT.write_text(text)
    print(block)


if __name__ == "__main__":
    main()
