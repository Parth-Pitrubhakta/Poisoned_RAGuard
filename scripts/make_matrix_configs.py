"""Write the Step 3 NQ matrix configs to configs/matrix/ (2 retrievers x 3 LLMs, plus the reranker row).

  uv run python scripts/make_matrix_configs.py
"""
import copy
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
base = yaml.safe_load((ROOT / "configs" / "baseline_nq_full.yaml").read_text())

RETRIEVERS = {
    "contriever": {"key": "contriever", "score_function": "dot", "mode": "upstream_precomputed",
                   "precomputed": "upstream/results/beir_results/nq-contriever.json"},
    "qwen3emb8b": {"key": "qwen3-emb-8b", "score_function": "dot", "mode": "dense_index",
                   "index_dir": "data/indexes/nq-qwen3-emb-8b", "batch_size": 64},
}
# Sampling is held identical across LLMs (user instruction: temperature 0.1 for all; flag, don't tune).
COMMON = {"temperature": 0.1, "do_sample": True, "top_p": 1.0, "top_k": 50, "repetition_penalty": 1.0, "seed": 100,
          "gpu": "auto"}
LLMS = {
    "vicuna7b": {"key": "vicuna-7b-v1.3", "max_new_tokens": 150, "min_free_gb": 30, "gpu_memory_utilization": 0.30},
    # Reasoning models: 150 tokens would truncate the reasoning before any answer. The budget covers reasoning plus
    # answer, and ASR is scored on the post-split final answer only.
    "qwen35_27b": {"key": "qwen3.5-27b", "max_new_tokens": 4096, "min_free_gb": 110, "gpu_memory_utilization": 0.75,
                   "output_parser": "think_tags"},
    "gptoss120b": {"key": "gpt-oss-120b", "max_new_tokens": 4096, "min_free_gb": 120, "gpu_memory_utilization": 0.80,
                   "output_parser": "harmony"},
}
RERANK = {"key": "qwen3-reranker-4b", "first_stage_k": 20, "batch_size": 16, "max_length": 2048}


def write(name, retr, llm, reranker=None):
    c = copy.deepcopy(base)
    c["run_name"] = f"nq_{name}_full"
    c["retriever"] = copy.deepcopy(RETRIEVERS[retr])
    c["llm"] = {**COMMON, **LLMS[llm]}
    if reranker:
        c["reranker"] = reranker
    out = ROOT / "configs" / "matrix" / f"nq_{name}.yaml"
    out.parent.mkdir(exist_ok=True)
    out.write_text(f"# generated by scripts/make_matrix_configs.py — full upstream protocol (10 iter x M=10)\n" + yaml.safe_dump(c, sort_keys=False))
    return out


paths = []
for r in RETRIEVERS:
    for l in LLMS:
        paths.append(write(f"{r}_{l}", r, l))
for l in LLMS:
    paths.append(write(f"qwen3emb8b-rerank4b_{l}", "qwen3emb8b", l, RERANK))
print("\n".join(str(p.relative_to(ROOT)) for p in paths))
