"""Write the Step 5 defense configs to configs/defenses/ from the Step 3 matrix configs (same cells, one change each).

  uv run python scripts/make_defense_configs.py

Per cell (3 retrieval setups x 3 LLMs), only the defense block changes, except:
  * paraphrase: Contriever cells switch to the FAISS Contriever index (dense_index). Upstream's precomputed results
    exist only for the original queries. Step 3 A showed the index reproduces the precomputed top-k on 100/100 questions.
  * knowledge_expansion: rag.top_k = k. Reranker first stage = max(20, 2k). k=10 for every LLM. k=50 only for
    Qwen3.5-27B and gpt-oss-120b, since Vicuna-7B's 2048-token context cannot hold 50 passages; their max_model_len
    is raised to 16384 (the models support far more, and no new weights are needed).
  * GPU memory: a foreign process holds 36-64 GB per GPU (2026-11-20), so the large models get
    gpu_memory_utilization 0.68 / min_free_gb 97 (was 0.75-0.80 / 110-120). This only changes KV-cache size, not outputs.
Sampling is unchanged (T=0.1 for all LLMs).
"""
import copy
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
CELLS = [f"{r}_{l}" for r in ("contriever", "qwen3emb8b", "qwen3emb8b-rerank4b") for l in ("vicuna7b", "qwen35_27b", "gptoss120b")]
CONTRIEVER_DENSE = {"key": "contriever", "score_function": "dot", "mode": "dense_index",
                    "index_dir": "data/indexes/nq-contriever", "batch_size": 64}
PPL = {"lm": "vicuna-7b-v1.3", "calib_n": 1000, "fpr": 0.05}


def defenses_for(cell: str) -> list[tuple[str, dict, dict]]:
    """-> [(tag, defense block, extra overrides)]"""
    vic = cell.endswith("vicuna7b")
    out = [("dup", {"name": "duplicate_filter"}, {}),
           ("ppl", {"name": "perplexity_filter", "params": PPL}, {}),
           ("para", {"name": "paraphrase", "params": {"file": "experiments/defenses/paraphrases_nq.json", "which": 0}},
            {"paraphrase": True}),
           ("ke10", {"name": "knowledge_expansion", "params": {"k": 10}}, {"k": 10}),
           ("trustrag", {"name": "trustrag", "params": {"embedder": "contriever", "removal": "kmeans_ngram",
                                                         **({"stage_max_new_tokens": 512} if vic else {})}}, {}),
           # faithful TrustRAG embedder (SimCSE sup-bert, [CLS]); the "trustrag" tag above is the Contriever substitute
           ("trustrag-simcse", {"name": "trustrag", "params": {"embedder": "simcse-sup-bert", "removal": "kmeans_ngram",
                                                                **({"stage_max_new_tokens": 512} if vic else {})}}, {})]
    if not vic:
        out.insert(4, ("ke50", {"name": "knowledge_expansion", "params": {"k": 50}}, {"k": 50, "max_model_len": 16384}))
    return out


def main():
    written = []
    for cell in CELLS:
        base = yaml.safe_load((ROOT / "configs" / "matrix" / f"nq_{cell}.yaml").read_text())
        for tag, dfn, ov in defenses_for(cell):
            c = copy.deepcopy(base)
            c["run_name"] = f"nq_{cell}_{tag}_full"
            c["defense"] = dfn
            if c["llm"]["key"] != "vicuna-7b-v1.3":
                c["llm"].update(gpu_memory_utilization=0.68, min_free_gb=97)
            if ov.get("paraphrase") and c["retriever"]["mode"] == "upstream_precomputed":
                c["retriever"] = copy.deepcopy(CONTRIEVER_DENSE)
            if "k" in ov:
                c["rag"]["top_k"] = ov["k"]
                if c.get("reranker"):
                    c["reranker"]["first_stage_k"] = max(20, 2 * ov["k"])
            if "max_model_len" in ov:
                c["llm"]["max_model_len"] = ov["max_model_len"]
            out = ROOT / "configs" / "defenses" / tag / f"nq_{cell}.yaml"
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text("# generated by scripts/make_defense_configs.py — Step 5, full upstream protocol (10 iter x M=10)\n"
                           + yaml.safe_dump(c, sort_keys=False))
            written.append(out)
    print("\n".join(str(p.relative_to(ROOT)) for p in written))
    print(len(written), "configs")


if __name__ == "__main__":
    main()
