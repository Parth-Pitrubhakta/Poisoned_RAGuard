"""Step 5 defense table: every defended run vs. its undefended Step 3 twin (same retrieval setup x LLM, defense none, k=5).

  uv run python scripts/make_defense_results.py      # -> experiments/defenses/defense_table.{json,csv}, RESULTS.md DEFENSE block

For each pair: ASR (upstream exact; also typography-normalized), clean accuracy (exact; normalized), the change in each,
poison passages kept in the prompt, clean passages removed (from the no-attack top-k), empty-final-answer rate, and an
exact paired McNemar p-value on per-question attack success. For perplexity_filter runs it also reports the
detection ROC AUC of PPL (poison vs. clean passages in the poisoned top-k), the paper's metric.
"""
from __future__ import annotations

import csv
import json
import math
import re
from pathlib import Path

from prag.eval.metrics import attack_success_normalized as norm_hit

ROOT = Path(__file__).resolve().parents[1]
EXP = ROOT / "experiments"
OUT_DIR = EXP / "defenses"
RESULTS = EXP / "RESULTS.md"
START, END = "<!-- DEFENSE:START (generated by scripts/make_defense_results.py) -->", "<!-- DEFENSE:END -->"
SETUP = {(r"contriever", None): "Contriever (paper)", ("qwen3-emb-8b", None): "Qwen3-Emb-8B",
         ("qwen3-emb-8b", "qwen3-reranker-4b"): "Qwen3-Emb-8B + rerank"}
LLM_ORDER = ["vicuna-7b-v1.3", "qwen3.5-27b", "gpt-oss-120b"]
LLM_NAME = {"vicuna-7b-v1.3": "Vicuna-7B", "qwen3.5-27b": "Qwen3.5-27B", "gpt-oss-120b": "gpt-oss-120b"}
DEF_ORDER = ["duplicate_filter", "perplexity_filter", "paraphrase", "knowledge_expansion@10", "knowledge_expansion@50", "trustrag",
             "trustrag@contriever"]
DEF_NAME = {"duplicate_filter": "Duplicate filter", "perplexity_filter": "Perplexity filter (5% FPR)", "paraphrase": "Paraphrasing",
            "knowledge_expansion@10": "Knowledge expansion k=10", "knowledge_expansion@50": "Knowledge expansion k=50",
            "trustrag": "TrustRAG (SimCSE, faithful)", "trustrag@contriever": "TrustRAG (Contriever substitute)"}
STEP3_RE = re.compile(r"^nq_(contriever|qwen3emb8b|qwen3emb8b-rerank4b)_(vicuna7b|qwen35_27b|gptoss120b)_full-")


def traces(path: Path) -> list[dict]:
    return sorted((json.loads(l) for l in open(path / "traces.jsonl")), key=lambda t: (t["iteration"], t["question_id"]))


def mcnemar(a: list[bool], b: list[bool]) -> float:
    """Exact two-sided McNemar on paired booleans."""
    n01 = sum(x and not y for x, y in zip(a, b)); n10 = sum(y and not x for x, y in zip(a, b)); n = n01 + n10
    if n == 0:
        return 1.0
    k = min(n01, n10)
    return min(1.0, 2 * sum(math.comb(n, i) for i in range(k + 1)) / 2 ** n)


def auc(pos: list[float], neg: list[float]) -> float | None:
    """P(score_pos > score_neg) + 0.5 P(tie). 'Positive' = poison; a detector flags HIGH perplexity."""
    if not pos or not neg:
        return None
    gt = sum((p > q) + 0.5 * (p == q) for p in pos for q in neg)
    return gt / (len(pos) * len(neg))


def stats(T: list[dict]) -> dict:
    n = len(T)
    d = [t["defense"] if isinstance(t.get("defense"), dict) else {} for t in T]
    return {"asr": sum(t["success"] for t in T) / n,
            "asr_norm": sum(norm_hit(t["target_answer"], t["output_poisoned"]) for t in T) / n,
            "clean": sum(bool(t["clean_correct"]) for t in T) / n,
            "clean_norm": sum(norm_hit(t["correct_answer"], t["output_clean"] or "") for t in T) / n,
            "poison_topk": sum(sum(p["is_poison"] for p in t["retrieved_topk"]) for t in T) / n,
            "poison_kept": sum(x.get("poison_kept", sum(p["is_poison"] for p in t["retrieved_topk"])) for x, t in zip(d, T)) / n,
            "clean_removed": sum(x.get("clean_removed", 0) for x in d) / n,
            "empty_ctx": sum(len(x.get("kept_ranks", [0])) == 0 for x in d) / n,
            "empty_final": sum(not t["output_poisoned"].strip() for t in T) / n,
            # answered-only: excludes questions with an empty final answer (reasoning truncated), which the exact
            # metric scores as "attack failed". Separates real resistance from running out of tokens.
            "asr_answered": (lambda A: sum(t["success"] for t in A) / len(A) if A else None)([t for t in T if t["output_poisoned"].strip()]),
            "k": len(T[0]["retrieved_topk"]) if T else None}


def main() -> int:
    idx = json.loads((EXP / "index.json").read_text())["runs"]
    twins, defended = {}, {}
    for r in idx:
        if r.get("status") != "complete" or r.get("kind") != "pipeline" or r.get("dataset") != "nq":
            continue
        key = (SETUP.get((r["retriever"], r.get("reranker"))), r["llm"])
        if key[0] is None:
            continue
        dname = r.get("defense") or "none"
        if dname == "none":
            if STEP3_RE.match(r["run_id"]):
                twins[key] = r
            continue
        tag = f"{dname}@{r['top_k']}" if dname == "knowledge_expansion" else dname
        if dname == "trustrag":  # the embedder lives in summary.defense_params, not in index.json
            emb = json.loads((ROOT / r["path"] / "summary.json").read_text()).get("defense_params", {}).get("embedder")
            tag = "trustrag" if emb == "simcse-sup-bert" else f"trustrag@{emb}"
        defended[(tag,) + key] = r  # latest wins
    rows = []
    for (tag, setup, llm), r in defended.items():
        tw = twins.get((setup, llm))
        if tw is None:
            continue
        Td, Tb = traces(ROOT / r["path"]), traces(ROOT / tw["path"])
        if [(t["iteration"], t["question_id"]) for t in Td] != [(t["iteration"], t["question_id"]) for t in Tb]:
            raise SystemExit(f"question sets differ: {r['run_id']} vs {tw['run_id']}")
        a, b = stats(Td), stats(Tb)
        row = {"defense": tag, "retrieval": setup, "llm": llm, "llm_name": LLM_NAME.get(llm, llm), "k": a["k"],
               "asr_none": b["asr"], "asr_def": a["asr"], "d_asr": a["asr"] - b["asr"],
               "asr_norm_none": b["asr_norm"], "asr_norm_def": a["asr_norm"],
               "clean_none": b["clean"], "clean_def": a["clean"], "d_clean": a["clean"] - b["clean"],
               "clean_norm_none": b["clean_norm"], "clean_norm_def": a["clean_norm"],
               "poison_in_topk": a["poison_topk"], "poison_kept": a["poison_kept"], "clean_removed": a["clean_removed"],
               "empty_ctx": a["empty_ctx"], "empty_final": a["empty_final"], "empty_final_none": b["empty_final"],
               "asr_answered_none": b["asr_answered"], "asr_answered_def": a["asr_answered"],
               "discordant_asr": sum(x["success"] != y["success"] for x, y in zip(Tb, Td)),
               "p_mcnemar_asr": mcnemar([t["success"] for t in Tb], [t["success"] for t in Td]),
               "p_mcnemar_clean": mcnemar([bool(t["clean_correct"]) for t in Tb], [bool(t["clean_correct"]) for t in Td]),
               "run_id": r["run_id"], "twin_run_id": tw["run_id"]}
        if tag == "perplexity_filter":
            pos = [v for t in Td for p, v in zip(t["retrieved_topk"], t["defense"]["info"]["ppl"]) if p["is_poison"]]
            neg = [v for t in Td for p, v in zip(t["clean_topk"], t["defense"]["clean_info"]["ppl"]) if not p["is_poison"]]
            row["ppl_auc"] = auc(pos, neg)
            row["ppl_threshold"] = Td[0]["defense"]["info"]["threshold"]
        rows.append(row)
    order = lambda x: (DEF_ORDER.index(x["defense"]) if x["defense"] in DEF_ORDER else 99,  # noqa: E731
                       list(SETUP.values()).index(x["retrieval"]), LLM_ORDER.index(x["llm"]) if x["llm"] in LLM_ORDER else 9)
    rows.sort(key=order)
    robust = {"vicuna-7b-v1.3": ("asr_none", "asr_def", "exact"), "qwen3.5-27b": ("asr_answered_none", "asr_answered_def", "answered-only"),
              "gpt-oss-120b": ("asr_norm_none", "asr_norm_def", "typography-normalized")}
    for r in rows:
        a0, a1, name = robust.get(r["llm"], ("asr_none", "asr_def", "exact"))
        r.update(robust_none=r[a0], robust_def=r[a1], robust_metric=name)
    # noise floor: duplicate-filter runs change <= 1 prompt per 100, so their differences from the twin are run-to-run noise
    noise = {}
    for l in LLM_ORDER:
        rs = [r for r in rows if r["defense"] == "duplicate_filter" and r["llm"] == l]
        if rs:
            noise[l] = {"cells": len(rs), "max_abs_d_asr": max(abs(r["d_asr"]) for r in rs),
                        "max_abs_d_robust": max(abs(r["robust_def"] - r["robust_none"]) for r in rs),
                        "max_abs_d_clean": max(abs(r["d_clean"]) for r in rs),
                        "max_discordant": max(r["discordant_asr"] for r in rs)}
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "defense_table.json").write_text(json.dumps(
        {"rows": rows, "noise_floor": noise, "order": DEF_ORDER, "names": DEF_NAME,
         "note": "generated by scripts/make_defense_results.py; each row = defended run vs its undefended Step 3 twin"}, indent=2))
    if rows:
        with open(OUT_DIR / "defense_table.csv", "w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=sorted({k for r in rows for k in r}, key=lambda k: list(rows[0]).index(k) if k in rows[0] else 99))
            w.writeheader(); w.writerows(rows)

    f2 = lambda v: "—" if v is None else f"{v:.2f}"  # noqa: E731
    sg = lambda v: "—" if v is None else f"{v:+.2f}"  # noqa: E731
    md = [START, "", f"_{len(rows)} defended runs, each paired with its undefended Step 3 twin "
          "(same retrieval × LLM, 100 questions, full protocol). ASR and clean accuracy are the upstream exact metric; "
          "Δ = defended − undefended. `p` = exact paired McNemar on per-question attack success._", ""]
    # summary: mean over the 9 cells (or 6 for k=50)
    md += ["**Table D1 — mean over cells** (ASR ↓ is good, Δclean < 0 is the utility cost)", "",
           "| Defense | cells | ASR none → defended | ΔASR | answered-only ASR none → def | empty final none → def | clean acc none → defended | Δclean | poison kept / in top-k | clean removed (no attack) |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    for tag in DEF_ORDER:
        rs = [r for r in rows if r["defense"] == tag]
        if not rs:
            continue
        m = lambda k: sum(r[k] for r in rs) / len(rs)  # noqa: E731
        md.append(f"| {DEF_NAME[tag]} | {len(rs)} | {m('asr_none'):.2f} → {m('asr_def'):.2f} | {m('d_asr'):+.2f} | "
                  f"{m('asr_answered_none'):.2f} → {m('asr_answered_def'):.2f} | {m('empty_final_none'):.2f} → {m('empty_final'):.2f} | "
                  f"{m('clean_none'):.2f} → {m('clean_def'):.2f} | {m('d_clean'):+.2f} | {m('poison_kept'):.2f} / {m('poison_in_topk'):.2f} | {m('clean_removed'):.2f} |")
    md += ["", "**Table D2 — per LLM** (mean over the retrieval setups; ASR / clean acc, defended)", "",
           "| Defense | " + " | ".join(f"{LLM_NAME[l]} ASR | {LLM_NAME[l]} clean" for l in LLM_ORDER) + " |",
           "|---|" + "---|---|" * len(LLM_ORDER)]
    base = {l: [r for r in rows if r["llm"] == l and r["defense"] == DEF_ORDER[0]] or [r for r in rows if r["llm"] == l] for l in LLM_ORDER}
    cells = []
    for l in LLM_ORDER:
        b = base[l]
        cells.append(f"{f2(sum(r['asr_none'] for r in b) / len(b)) if b else '—'} | {f2(sum(r['clean_none'] for r in b) / len(b)) if b else '—'}")
    md.append("| _none (Step 3)_ | " + " | ".join(cells) + " |")
    for tag in DEF_ORDER:
        cells = []
        for l in LLM_ORDER:
            rs = [r for r in rows if r["defense"] == tag and r["llm"] == l]
            cells.append(f"{f2(sum(r['asr_def'] for r in rs) / len(rs)) if rs else '—'} | {f2(sum(r['clean_def'] for r in rs) / len(rs)) if rs else '—'}")
        if any(c != "— | —" for c in cells):
            md.append(f"| {DEF_NAME[tag]} | " + " | ".join(cells) + " |")
    md += ["", "**Table D2b — per LLM, ASR that is robust to the two known scoring artifacts** "
           "(Qwen3.5: answered-only, because truncated reasoning scores as 'failed'; gpt-oss: typography-normalized, because "
           "U+202F spaces hide exact matches; Vicuna: exact). Mean over retrieval setups.", "",
           "| Defense | Vicuna-7B (exact) | Qwen3.5-27B (answered-only) | gpt-oss-120b (normalized) |", "|---|---|---|---|"]
    robust = {"vicuna-7b-v1.3": ("asr_none", "asr_def"), "qwen3.5-27b": ("asr_answered_none", "asr_answered_def"),
              "gpt-oss-120b": ("asr_norm_none", "asr_norm_def")}
    for tag in DEF_ORDER:
        cells = []
        for l in LLM_ORDER:
            rs = [r for r in rows if r["defense"] == tag and r["llm"] == l]
            a0, a1 = robust[l]
            cells.append(f"{sum(r[a0] for r in rs) / len(rs):.2f} → {sum(r[a1] for r in rs) / len(rs):.2f}" if rs else "—")
        md.append(f"| {DEF_NAME[tag]} | " + " | ".join(cells) + " |")
    md += ["", "**Table D3 — every run**", "",
           "| Defense | Retrieval | LLM | k | ASR none → def (Δ) | p | normalized ASR none → def | answered-only ASR none → def | clean none → def (Δ) | poison kept / top-k | clean removed | empty ctx | empty final none → def |",
           "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        md.append(f"| {DEF_NAME.get(r['defense'], r['defense'])} | {r['retrieval']} | {r['llm_name']} | {r['k']} | "
                  f"{f2(r['asr_none'])} → {f2(r['asr_def'])} ({sg(r['d_asr'])}) | {r['p_mcnemar_asr']:.3f} | "
                  f"{f2(r['asr_norm_none'])} → {f2(r['asr_norm_def'])} | {f2(r['asr_answered_none'])} → {f2(r['asr_answered_def'])} | "
                  f"{f2(r['clean_none'])} → {f2(r['clean_def'])} ({sg(r['d_clean'])}) | "
                  f"{r['poison_kept']:.2f} / {r['poison_in_topk']:.2f} | {r['clean_removed']:.2f} | {r['empty_ctx']:.2f} | {r['empty_final_none']:.2f} → {r['empty_final']:.2f} |")
    if noise:
        md += ["", "**Noise floor** (duplicate filter ≈ identical prompts, so these are run-to-run differences): "
               + "; ".join(f"{LLM_NAME[l]} max |ΔASR| {v['max_abs_d_asr']:.2f}, max |Δclean| {v['max_abs_d_clean']:.2f}, "
                           f"≤ {v['max_discordant']} discordant questions" for l, v in noise.items())
               + ". Treat |Δ| ≲ 0.05 for the reasoning models as noise."]
    ppl = [r for r in rows if r.get("ppl_auc") is not None]
    if ppl:
        md += ["", "**Perplexity detection (paper's metric)**: ROC AUC of Vicuna-7B PPL, poison (positive) vs. clean passages: "
               + ", ".join(f"{r['retrieval']} × {r['llm_name']} {r['ppl_auc']:.2f}" for r in ppl if r["llm"] == LLM_ORDER[0])
               + f". Threshold (95th pct of 1,000 random NQ passages) = {ppl[0]['ppl_threshold']:.1f}. "
               "AUC 0.5 = chance; below 0.5 means poison has *lower* perplexity than clean text."]
    md += ["", END]
    block = "\n".join(md)
    text = RESULTS.read_text()
    if START in text:
        text = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    else:
        text += "\n\n## Step 5 — defenses\n\n" + block + "\n"
    RESULTS.write_text(text)
    print(block)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
